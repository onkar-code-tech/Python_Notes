# What is variable:
'''variable is like a container that holds data. '''
'''Creating a variable is like creating a placeholder in memory and assigning it some value.'''
'''You create a variable by assigning a value using the '=' operator'''
# For example:
a = "onkar"
b = 20
c = True
d = None

# Variable Types
'''Python automatically determines the type of data:'''
# Example:

x = 10          # Integer (int)
y = 3.14        # Float (float)
name = "John"   # String (str)
is_student = True  # Boolean (bool)

print(a,b,c,d,x,y,name,is_student, sep="\n")